import { unified } from 'unified'
import remarkParse from 'remark-parse'
import remarkGfm from 'remark-gfm'
import remarkMath from 'remark-math'
import remarkRehype from 'remark-rehype'
import rehypeRaw from 'rehype-raw'
import rehypeSanitize from 'rehype-sanitize'
import rehypeSlug from 'rehype-slug'
import rehypeAutolinkHeadings from 'rehype-autolink-headings'
import rehypeHighlight from 'rehype-highlight'
import rehypeKatex from 'rehype-katex'
import rehypeStringify from 'rehype-stringify'
import { schema } from './schema.js'
import { octicon } from './icons.js'
import rehypeAlerts from './plugins/alerts.js'
import rehypeRewriteUrls from './plugins/rewrite-urls.js'
import rehypeHashLinks from './plugins/hash-links.js'

export interface RenderOptions {
  /** Resolve relative image / media URLs against this absolute URL. */
  baseUrl?: string
  /** Resolve relative link URLs against this absolute URL. Defaults to `baseUrl`. */
  linkBaseUrl?: string
}

/**
 * Markdown string -> sanitized, GitHub-style HTML.
 *
 * Order matters: user HTML is sanitized first; everything added after
 * (anchors, highlighting, KaTeX, alerts) is generated by us and trusted.
 */
export async function renderMarkdown(
  markdown: string,
  options: RenderOptions = {},
): Promise<string> {
  const file = await unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(remarkMath)
    .use(remarkRehype, { allowDangerousHtml: true, clobberPrefix: '' }) // sanitize adds the prefix
    .use(rehypeRaw)
    .use(rehypeSanitize, schema)
    .use(rehypeRewriteUrls, options)
    .use(rehypeSlug)
    .use(rehypeAutolinkHeadings, {
      // the footnotes label is visually hidden; GitHub gives it no anchor
      test: (node) => !(node.properties?.className as string[] | undefined)?.includes('sr-only'),
      behavior: 'prepend',
      properties: { className: ['anchor'], ariaHidden: 'true' },
      content: () => octicon('link'),
    })
    .use(rehypeHashLinks)
    .use(rehypeHighlight, { plainText: ['mermaid'] })
    .use(rehypeKatex) // invalid TeX renders inline in red instead of throwing
    .use(rehypeAlerts)
    .use(rehypeStringify)
    .process(markdown)
  return String(file)
}
